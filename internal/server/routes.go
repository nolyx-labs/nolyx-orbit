	auth("POST /api/v1/projects/{pid}/provisions", s.createProvision)
	auth("DELETE /api/v1/projects/{pid}/provisions/{id}", s.destroyProvision)

	s.apiHandler = s.requireUser(api)
	mux.Handle("/api/v1/", s.apiHandler)
	mux.HandleFunc("/mcp", s.mcp)
	mux.Handle("POST /api/v1/auth/signup", s.h(s.signup))
	mux.Handle("POST /api/v1/auth/login", s.h(s.login))
